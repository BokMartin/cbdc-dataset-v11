#!/usr/bin/env python3
"""Keep the numbers in PROJECT_BRIEF.md true: the block between the NUMBERS markers is generated from the repository's own files.

Nothing in the block is typed by hand. `--check` exits with an error when the block in the file differs from what the data say
(run in CI), so a session that changes the data without updating the brief cannot be pushed green.

usage: update_brief.py            rewrite the block
       update_brief.py --check    verify it is current
"""
import collections, csv, glob, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
B, E = "<!-- NUMBERS:BEGIN (generated by scripts/pipeline/update_brief.py; do not edit by hand) -->", "<!-- NUMBERS:END -->"
latest = lambda pat: sorted(glob.glob(os.path.join(ROOT, pat)))[-1]
rows = lambda f: list(csv.DictReader(open(f, encoding="utf-8")))
n = lambda x: f"{x:,}".replace(",", " ")
day = lambda f: re.search(r"(\d{4}-\d{2}-\d{2})", os.path.basename(f)).group(1)


def judgement(files):
    if not files: return "**not yet returned** (86 matched pairs + 30 unmatched sentences registered)"
    parts = []
    for f in sorted(files):
        d = json.load(open(f)); w = d["weighted_share_all_163_matched"]
        parts.append(f"{d.get('judge', '?')}: same meaning and strength {w['S']:.0%}, weaker {w['W']:.0%}, stronger {w['X']:.0%}, meaning differs {w['M']:.0%}")
    ag = glob.glob(os.path.join(ROOT, "data/translation/benchmark/JUDGEMENT_AGREEMENT_*.json"))
    two = json.load(open(sorted(ag)[-1]))["two_judges"] if ag else None
    return ("matched pairs, weighted to 163 matched sentences, judgeable pairs only · " + " · ".join(parts) +
            (f" · **the two judges agree on {two['raw_agreement']:.0%} of the 86 pairs (Cohen's kappa {two['cohen_kappa']:.2f}); not adjudicated**" if two else " · one judge"))


def dev_agreement():
    f = sorted(glob.glob(os.path.join(ROOT, "data/units/DEV_AGREEMENT_RELEVANCE_*.json")))
    if not f: return "scored: **not yet**"
    d = json.load(open(f[-1])); a, b = d["all"], d["all_without_U_pairs"]
    return (f"relevance coded blind by {d['coder_a']} and {d['coder_b']} ({d['both_coded']} units both coded): agreement {a['agreement']:.0%}, Krippendorff's alpha {a['alpha']:.2f} "
            f"(below the 0.667 of the protocol); without the pairs that hold a U: {b['n']} units, agreement {b['agreement']:.0%}, alpha {b['alpha']:.2f}; facets not coded")


def block():
    C = collections.Counter
    fr = rows(os.path.join(ROOT, "data/frame/projects.csv")); n_frame = sum(r["analytic_frame"] == "True" for r in fr); n_nat = sum(r["retail_candidate"] == "True" for r in fr)
    tf = latest("data/manifest/TIERS_*.csv"); T = rows(tf); inf = [r for r in T if r["tier"] != "out_of_frame"]
    ev = [r for r in inf if r["decision_v12"] in ("KEEP", "BORDERLINE")]; ids = {r["id"] for r in ev}; pubs = [r for r in ev if r["same_publication_as"] not in ids]
    by_author = sum(not r["decision_source"].startswith("model") for r in ev)
    tiers = collections.defaultdict(set)
    for r in inf: tiers[r["tier"]].add(r["project"])
    comp = rows(latest("data/manifest/COMPANION_LINKS_*.csv")); uf = latest("data/units/UNITS_MANIFEST_*.csv"); U = rows(uf); cand = rows(latest("data/units/CANDIDATES_*.csv"))
    nu = [r for r in rows(latest("data/units/UNITS_NOT_UNITISED_*.csv")) if "same publication" not in r["reason"]]
    route = C(r["route"] for r in U); s = lambda k: sum(int(r[k]) for r in cand)
    inc_ids = {r["id"] for r in T if r["decision_v12"] == "INCLINED"}; n_inc = sum(r["id"] in inc_ids for r in U)  # documents with units that are not confirmed evidence (ADR-010)
    runs = sorted(glob.glob(os.path.join(ROOT, "data/translation/runs/*/RUN_META.json"))); calls = sum(json.load(open(f)).get("calls", 0) for f in runs)
    tm = [r for f in sorted(glob.glob(os.path.join(ROOT, "data/translation/TRANSLATION_MANIFEST_*.csv"))) for r in rows(f)]
    tdocs = {r["doc_key"] for r in tm if r["status"] == "ok" and r["priority"] != "BENCH"}
    dev = glob.glob(os.path.join(ROOT, "data/units/AGREEMENT_SAMPLE_dev_*.csv")); main = glob.glob(os.path.join(ROOT, "data/units/AGREEMENT_SAMPLE_main_*.csv"))
    scored = glob.glob(os.path.join(ROOT, "data/units/AGREEMENT_RESULT_*.json")); judged = glob.glob(os.path.join(ROOT, "data/translation/benchmark/JUDGEMENT_RESULT_*.json"))
    ncand = sum(r["decision_v12"] == "CANDIDATE" for r in T); cand_note = f" or, for {ncand} candidates, awaiting one" if ncand else ""
    master = rows(latest("data/manifest/MASTER_MANIFEST_*.csv")); tests = sum(len(re.findall(r"(?m)^def test_", open(f, encoding="utf-8").read())) for f in glob.glob(os.path.join(ROOT, "tests/test_*.py")))
    L = [B, f"State of the data files as of **{max(day(tf), day(uf))}** (dates are those of the files, not of the day you read this).", "",
         "| | |", "|---|---|",
         f"| Analytic frame | **{n_frame} projects** = {n_nat} national retail candidates + the digital euro |",
         f"| Official documents collected | {len(master)} files in the master folder; {len(T)} document rows, each with an author or model decision{cand_note} |",
         f"| Evidence documents (in the frame) | **{len(pubs)} publications** ({len(ev)} rows); {by_author} of {len(ev)} decided or confirmed by an author |",
         f"| Companion documents (in the frame) | {len(comp)}, cited for status and timeline; linked to evidence of the same year {sum(r['link_basis'] == 'same year' for r in comp)}, of the nearest year {sum(r['link_basis'].startswith('nearest') for r in comp)}, no link {sum(not (r['link_basis'] == 'same year' or r['link_basis'].startswith('nearest')) for r in comp)}; {sum(r['decision_source'].startswith('author') for r in comp)} reviewed by an author |",
         f"| Tiers by number of evidence publications | T1 (8+): {len(tiers['T1'])} · {', '.join(sorted(tiers['T1']))}<br>T2 (5 to 7): {len(tiers['T2'])} · {', '.join(sorted(tiers['T2']))}<br>T3 (4 or fewer): {len(tiers['T3'])} |",
         f"| English text for measurement | {len(U)} documents of {len({r['project'] for r in U})} projects ({len(U) - n_inc} evidence publications and {n_inc} INCLINED documents, ADR-010): {route['A']} English originals, {route['B']} issuer English editions, {route['D']} machine translations; {len(nu)} evidence documents still without English text |",
         f"| Machine translation | {len(runs)} API runs, {calls} calls, {len(tdocs)} documents translated (benchmark translations excluded) |",
         f"| Sentence units | {n(sum(int(r['units']) for r in U))} units; {n(s('D') + s('N') + s('R'))} candidates for classification (dictionary hits {n(s('D'))}, neighbours {n(s('N'))}, random control {n(s('R'))}) |",
         f"| Human coding | development sample: {'drawn, ' + str(len(rows(dev[-1]))) + ' units' if dev else 'not drawn'}; {dev_agreement()} · reference sample (400): {'drawn' if main else 'not drawn'} |",
         f"| Human judgement of translation | {judgement(judged)} |",
         f"| Model classification of units | {'run' if glob.glob(os.path.join(ROOT, 'data/units/L1_*')) else '**not started** (no unit has been labelled by a model)'} |",
         f"| Tests in CI | {tests} |", E]
    return "\n".join(L)


def main():
    p = os.path.join(ROOT, "PROJECT_BRIEF.md"); s = open(p, encoding="utf-8").read(); i, j = s.index(B), s.index(E) + len(E); new = s[:i] + block() + s[j:]
    if "--check" in sys.argv:
        if new != s: raise SystemExit("PROJECT_BRIEF.md: the numbers block is stale; run scripts/pipeline/update_brief.py")
        print("PROJECT_BRIEF.md numbers are current")
    else:
        open(p, "w", encoding="utf-8").write(new); print("PROJECT_BRIEF.md updated")


if __name__ == "__main__": main()
