"""Write archive/INDEX.md: every dated file family in the tree, which version is current, which are superseded.

Superseded dated files stay where they are (ADR-020): scripts find inputs by date (latest match), audits and ADRs name
the exact file they read, and git history alone is not a reader's index. A family is the file name with its date
(YYYY-MM-DD plus an optional letter) removed. The latest date in a family is "current"; every earlier one is
"superseded by" the next. Files listed in HISTORICAL are retired lines kept as records.

  python scripts/provenance/build_archive_index.py          # write
  python scripts/provenance/build_archive_index.py --check  # fail if archive/INDEX.md is stale
"""
import collections, hashlib, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "archive", "INDEX.md")
DATE = re.compile(r"_?(20\d\d-\d\d-\d\d[a-z]?)")
SCAN = ("data/", "docs/", "DECISIONS/")
SKIP = ("docs/audits/", "data/talk/runs/", "data/extraction/runs/", "data/translation/runs/", "data/worked_profiles/", "data/index/mock/")

# Families in which every dated file is a separate record (each adds rows); none supersedes another.
RECORDS = {"data/manifest/AUTHOR_DECISIONS.csv", "data/manifest/AUTHOR_CONFIRMATIONS.csv"}

HISTORICAL = [
    ("archive/v11/", "v11 line (contract v1.1, core rubric, predictions, core_v1 freeze); replaced by v12 on 3 Nov 2026", "METHOD.md, README.md, ADR-001"),
    ("archive/run_scripts/", "hash-verified earlier versions of scripts/extraction/extract_api.py used by the v1.1 development runs", "data/worked_profiles/*/MANIFEST.json"),
    ("schema/cells_v1_1.json", "cell schema of the v1.1 development runs (2 to 10 Nov 2026); production uses schema/cells_v12_DRAFT.json and prompt v12.2", "ADR-002, ADR-003"),
    ("data/worked_profiles/", "development profiles NO and UK under contract v1.1 and v12 draft (2 to 10 Nov 2026), including the full Norges Bank texts sent to the model (reproduction with attribution, ADR-020)", "ADR-002, ADR-003, EXPOSURE_LEDGER.md"),
    ("scripts/extraction/extract_api.py", "extractor of the development runs; production uses scripts/pipeline/runner.py with scripts/extraction/v122.py", "pipeline/README.md, archive/run_scripts/"),
    ("scripts/pipeline/run_all.py", "one-command re-run of the v1.1 / v12-draft development extraction", "pipeline/README.md"),
    ("pipeline/prompts/extraction_single.system.md", "extraction prompt of the development runs (before v12.1 and v12.2)", "audits of 17 and 23 Nov"),
    ("pipeline/prompts/extraction_stage1.system.md", "two-stage extraction prompt, stage 1, development only", "audit of 17 Nov"),
    ("pipeline/prompts/extraction_stage2_synthesis.system.md", "two-stage extraction prompt, stage 2, development only", "audit of 17 Nov"),
    ("data/index/mock/", "synthetic (MOCK) projects used to design and test the privacy index before any real data; not results", "ADR-009, docs/PRIVACY_INDEX_SPEC_DRAFT_2026-11-21.md"),
    ("scripts/index_mock.py", "generator of the synthetic index data", "data/index/mock/"),
]


def sha(p):
    return hashlib.sha256(open(os.path.join(ROOT, p), "rb").read()).hexdigest()


def tracked():
    return subprocess.check_output(["git", "ls-files"], cwd=ROOT, text=True).split("\n")


def build():
    fam = collections.defaultdict(list)
    for f in tracked():
        if not f.startswith(SCAN) or f.startswith(SKIP) or f.startswith("DECISIONS/"):
            continue
        m = DATE.search(os.path.basename(f))
        if not m:
            continue
        key = os.path.join(os.path.dirname(f), DATE.sub("", os.path.basename(f), count=1))
        fam[key].append((m.group(1), f))
    L = ["# Index of dated and historical files", "",
         "Generated by `scripts/provenance/build_archive_index.py`; CI checks that it is current. Policy: [ADR-020](../DECISIONS/ADR-020-repository-record-and-cleanup-2026-11-27.md).",
         "Nothing listed here is deleted. A superseded file stays at its path because scripts select inputs by date and audits and",
         "decisions cite the exact file they read. Use the **current** file unless you are reconstructing an earlier stage.", "",
         "## 1. Dated file families with more than one version", "",
         "| Family | Version | State | SHA-256 (first 16) |", "|---|---|---|---|"]
    single = []
    for key in sorted(fam):
        vs = sorted(fam[key])
        if len(vs) == 1:
            single.append(vs[0][1]); continue
        for i, (d, f) in enumerate(vs):
            if key in RECORDS:
                state = "dated record, valid alongside the others"
            else:
                state = "**current**" if i == len(vs) - 1 else f"superseded by {vs[i + 1][0]}"
            L.append(f"| `{key}` | [{d}](../{f}) | {state} | `{sha(f)[:16]}` |")
    L += ["", "## 2. Retired lines kept as records", "",
          "These are not used by the production pipeline of 23 and 24 Nov 2026. They stay because ADRs, audits and the run",
          "statement cite them, and some tests still exercise them.", "",
          "| Path | What it is | Cited by |", "|---|---|---|"]
    tr = set(tracked())
    for p, what, by in HISTORICAL:
        if p in tr or any(t.startswith(p) for t in tr):
            L.append(f"| [`{p}`](../{p}) | {what} | {by} |")
    L += ["", f"## 3. Dated files with a single version ({len(single)})", "",
          "Each is the only version of its family and therefore current, unless a document names it as a dated record.", ""]
    L += [f"- `{f}`" for f in sorted(single)]
    return "\n".join(L) + "\n"


def main():
    new = build()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != new:
            raise SystemExit("archive/INDEX.md is stale; run scripts/provenance/build_archive_index.py")
        print("archive/INDEX.md is current"); return
    open(OUT, "w", encoding="utf-8", newline="\n").write(new); print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
